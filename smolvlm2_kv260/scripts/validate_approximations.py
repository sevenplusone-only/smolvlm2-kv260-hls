def approx_rsqrt_q15(x):
    if x <= 1:
        return Q15_ONE
    msb = x.bit_length() - 1
    norm_q6 = (x >> (msb - 6)) if msb >= 6 else (x << (6 - msb))
    norm_q6 = min(max(norm_q6, 64), 127)
    value = kRsqrtLutQ15[norm_q6 - 64]
    if msb & 1:
        value = (value * Q15_INV_SQRT2) >> 15
    value >>= (msb >> 1)
    return max(value, 1)


def approx_exp_q15(x_scaled):
    if x_scaled >= 0:
        return Q15_ONE
    dist = -x_scaled
    if dist >= len(kExpNegLutQ15):
        return 0
    return kExpNegLutQ15[dist]


def approx_silu_q8_8(x_scaled):
    if x_scaled <= -SILU_X_CLAMP:
        return kSiluLutQ8_8[0]
    if x_scaled >= SILU_X_CLAMP:
        return kSiluLutQ8_8[-1]
    shifted = x_scaled + SILU_X_CLAMP
    idx = shifted >> SILU_LUT_STEP_LOG2
    frac = shifted & ((1 << SILU_LUT_STEP_LOG2) - 1)
    y0 = kSiluLutQ8_8[idx]
    y1 = kSiluLutQ8_8[idx + 1]
    return y0 + ((y1 - y0) * frac + 2) // 4


def quarter_wave_lookup_q15(phase_quarter):
    quarter = 1 << ROPE_QUARTER_BITS
    if phase_quarter >= quarter:
        return Q15_ONE
    idx = phase_quarter >> ROPE_INTERP_BITS
    frac = phase_quarter & ((1 << ROPE_INTERP_BITS) - 1)
    y0 = kQuarterSinLutQ15[idx]
    y1 = kQuarterSinLutQ15[idx + 1]
    return y0 + ((y1 - y0) * frac + (1 << (ROPE_INTERP_BITS - 1))) // (1 << ROPE_INTERP_BITS)


def sin_turns_q15(phase_turns):
    quadrant = phase_turns >> ROPE_QUARTER_BITS
    offset = phase_turns & ((1 << ROPE_QUARTER_BITS) - 1)
    reflected = ((1 << ROPE_QUARTER_BITS) - offset) if (quadrant & 1) else offset
    mag = quarter_wave_lookup_q15(reflected)
    return -mag if (quadrant & 2) else mag


def cos_turns_q15(phase_turns):
    return sin_turns_q15((phase_turns + (1 << ROPE_QUARTER_BITS)) & 0xFFFFFFFF)


def approx_rope_sincos_q15(pair_idx, pos):
    phase_turns = (kRopeStepTurnsQ32[pair_idx] * pos) & 0xFFFFFFFF
    return cos_turns_q15(phase_turns), sin_turns_q15(phase_turns)


def check_rmsnorm():
    random.seed(0)
    max_err = 0.0
    mean_err = 0.0
    trials = 256
    for _ in range(trials):
        xs = [random.randint(-1024, 1023) for _ in range(960)]
        rms2 = sum(x * x for x in xs) // len(xs)
        approx = approx_rsqrt_q15(max(rms2, 1)) << 8
        ref = int(round((1.0 / math.sqrt(max(rms2, 1))) * (1 << 23)))
        err = abs(approx - ref) / max(ref, 1)
        max_err = max(max_err, err)
        mean_err += err
    return max_err, mean_err / trials


def check_exp():
    max_err = 0.0
    mean_err = 0.0
    count = 0
    for x in range(-511, 1):
        approx = approx_exp_q15(x) / Q15_ONE
        ref = math.exp(x / 64.0)
        err = abs(approx - ref) / max(ref, 1e-8)
        max_err = max(max_err, err)
        mean_err += err
        count += 1
    return max_err, mean_err / count


def check_silu():
    max_err = 0.0
    mean_err = 0.0
    count = 0
    for x in range(-768, 769):
        approx = approx_silu_q8_8(x) / 256.0
        real_x = x / 64.0
        ref = real_x / (1.0 + math.exp(-real_x))
        err = abs(approx - ref)
        max_err = max(max_err, err)
        mean_err += err
        count += 1
    return max_err, mean_err / count


def check_rope():
    max_err = 0.0
    mean_err = 0.0
    count = 0
    positions = [0, 1, 7, 31, 127, 511, 2047]
    for d in range(32):
        theta = 1.0 / (10000.0 ** ((2.0 * d) / 64.0))
        for pos in positions:
            cv, sv = approx_rope_sincos_q15(d, pos)
            ref_c = math.cos(pos * theta)
            ref_s = math.sin(pos * theta)
            for got, ref in ((cv / Q15_ONE, ref_c), (sv / Q15_ONE, ref_s)):
                err = abs(got - ref)
                max_err = max(max_err, err)
                mean_err += err
                count += 1
    return max_err, mean_err / count


def check_manifest_aliases(manifest_path):
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    tensors = manifest.get("native_backend", {}).get("tensors", [])
    names = [t["name"] for t in tensors]
    duplicates = len(names) - len(set(names))
    required = {"output.weight", "output"}
    missing = sorted(required.difference(names))
    return duplicates, missing


def main():
    rms_max, rms_mean = check_rmsnorm()
    exp_max, exp_mean = check_exp()
    silu_max, silu_mean = check_silu()
    rope_max, rope_mean = check_rope()

    print("Approximation checks")
    print("  RMSNorm rsqrt relerr: max=%.4f mean=%.4f" % (rms_max, rms_mean))
    print("  exp relerr:           max=%.4f mean=%.4f" % (exp_max, exp_mean))
    print("  SiLU abs err:         max=%.4f mean=%.4f" % (silu_max, silu_mean))
    print("  RoPE abs err:         max=%.4f mean=%.4f" % (rope_max, rope_mean))

    manifest_path = Path(__file__).resolve().parent.parent / "quantized_weights" / "manifest.json"
    if manifest_path.exists():
        duplicates, missing = check_manifest_aliases(manifest_path)
        print("Manifest checks")
        print("  duplicate names:      %d" % duplicates)
        print("  missing required:     %s" % (missing if missing else "none"))
    else:
        print("Manifest checks skipped: %s not found" % manifest_path)


if __name__ == "__main__":
    main()
